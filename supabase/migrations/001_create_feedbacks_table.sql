-- 파일명: 001_create_feedbacks_table.sql
-- 목적: 사용자가 남긴 식사 메뉴 추천 서비스 피드백(닉네임, 내용, 작성일시) 저장 테이블 생성
-- 실행 위치: Supabase 대시보드 -> 왼쪽 메뉴 [SQL Editor] -> New query 실행
-- ==============================================================================

-- 1. feedbacks 테이블 생성
CREATE TABLE IF NOT EXISTS public.feedbacks (
    -- id: 고유 식별자 (자동 증가 정수)
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    
    -- nickname: 작성자 닉네임 (미입력 시 '익명' 기본값)
    nickname TEXT DEFAULT '익명',
    
    -- content: 사용자가 작성한 피드백 본문
    content TEXT NOT NULL,
    
    -- created_at: 피드백 작성 일시 (UTC 기준 자동 생성)
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. 최신 피드백 조회를 위한 인덱스 생성
CREATE INDEX IF NOT EXISTS idx_feedbacks_created_at ON public.feedbacks (created_at DESC);

-- 3. 테이블 및 컬럼 한글 설명 추가 (교육용)
COMMENT ON TABLE public.feedbacks IS '식사 메뉴 랜덤 추천기 사용자 피드백 목록';
COMMENT ON COLUMN public.feedbacks.id IS '피드백 고유 식별자';
COMMENT ON COLUMN public.feedbacks.nickname IS '작성자 닉네임 (기본값: 익명)';
COMMENT ON COLUMN public.feedbacks.content IS '피드백 내용';
COMMENT ON COLUMN public.feedbacks.created_at IS '작성 일시';

-- 4. 행 단위 보안(RLS) 활성화
ALTER TABLE public.feedbacks ENABLE ROW LEVEL SECURITY;

-- 5. 보안 정책: 비회원(누구나) 피드백 조회(SELECT) 허용
CREATE POLICY "Anyone can read feedbacks" 
ON public.feedbacks 
FOR SELECT 
TO anon, authenticated 
USING (true);

-- 6. 보안 정책: 비회원(누구나) 피드백 등록(INSERT) 허용
CREATE POLICY "Anyone can insert feedback" 
ON public.feedbacks 
FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

